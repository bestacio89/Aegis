using Aegis.Shared.Architecture.Enums;

namespace Aegis.Shared.Architecture.Models;

/// <summary>
/// 🧭 Describes the inferred architectural, technological, and structural profile
/// of a project. Generated deterministically by Aegis before evaluation.
/// 
/// This context acts as the single source of truth for evaluators:
/// language rules, framework rules, architecture rules, and layer analysis.
/// </summary>
public sealed class ProjectArchitectureContext
{
    // ===============================================================
    // 🔖 Identity
    // ===============================================================

    public string ProjectName { get; set; } = string.Empty;

    public string RootPath { get; set; } = string.Empty;


    // ===============================================================
    // 🧩 Technology Detection
    // ===============================================================

    /// <summary>
    /// Primary detected language.
    /// Examples: C#, Java, Python, TypeScript.
    /// </summary>
    public string Language { get; set; } = "Unknown";


    /// <summary>
    /// Detected primary framework.
    /// Examples:
    /// .NET 9, Spring Boot, Angular, Django
    /// </summary>
    public string? Framework { get; set; }


    public string? TargetRuntime { get; set; }


    public ArchitectureBuildSystem BuildSystem { get; set; }
        = ArchitectureBuildSystem.Unknown;


    public List<string> DetectedFrameworks { get; set; } = new();

    /// <summary>
    /// Indicates whether frontend framework discovery completed without
    /// unreadable or malformed package manifests. A negative result means
    /// absence of frontend signals cannot establish rule inapplicability.
    /// </summary>
    public bool FrontendFrameworkDiscoveryComplete { get; set; }

    public List<string> DetectedDependencies { get; set; } = new();



    // ===============================================================
    // 🏗️ Structural Discovery
    // ===============================================================

    /// <summary>
    /// Detected modules/projects/packages.
    /// </summary>
    public List<ProjectModuleContext> Modules { get; set; } = new();

    /// <summary>Modules that belong to the production architecture.</summary>
    public IReadOnlyList<ProjectModuleContext> ProductionModules =>
        Modules.Where(module =>
            !module.IsTestProject
            && !module.IsTestSupport
            && !string.Equals(module.Type, "Test", StringComparison.OrdinalIgnoreCase)
            && !string.Equals(module.Type, "TestSupport", StringComparison.OrdinalIgnoreCase)
            && !string.Equals(module.ProjectKind, "Test", StringComparison.OrdinalIgnoreCase)
            && !string.Equals(module.ProjectKind, "TestSupport", StringComparison.OrdinalIgnoreCase))
        .ToArray();

    /// <summary>Test projects retained for source analysis and evidence.</summary>
    public IReadOnlyList<ProjectModuleContext> TestModules =>
        Modules.Where(module =>
            module.IsTestProject
            || string.Equals(module.Type, "Test", StringComparison.OrdinalIgnoreCase)
            || string.Equals(module.ProjectKind, "Test", StringComparison.OrdinalIgnoreCase))
        .ToArray();

    /// <summary>Reusable test-support packages, distinct from test projects.</summary>
    public IReadOnlyList<ProjectModuleContext> TestSupportModules =>
        Modules.Where(module =>
            module.IsTestSupport
            || string.Equals(module.Type, "TestSupport", StringComparison.OrdinalIgnoreCase)
            || string.Equals(module.ProjectKind, "TestSupport", StringComparison.OrdinalIgnoreCase))
        .ToArray();


    /// <summary>
    /// Logical architecture layers detected.
    /// Examples:
    /// API
    /// Application
    /// Contracts
    /// Domain
    /// Infrastructure
    /// Tests
    /// </summary>
    public List<ProjectLayerContext> Layers { get; set; } = new();


    public string? EntryPointFile { get; set; }


    public bool IsMultiModule =>
        ProductionModules.Count > 1;



    // ===============================================================
    // 🧱 Architecture Detection
    // ===============================================================

    public string? ArchitectureStyle { get; set; }

    public string? DomainType { get; set; }

    public string? Nature { get; set; }


    /// <summary>
    /// Detected architectural patterns.
    /// Examples:
    /// CQRS
    /// Repository
    /// Mediator
    /// Clean Architecture
    /// MVC
    /// </summary>
    public List<string> PatternsDetected { get; set; } = new();



    /// <summary>
    /// Detected architecture boundaries.
    /// Generated by BoundaryDetector.
    /// Used by evaluators to validate allowed architectural relations.
    /// </summary>
    public List<ArchitectureBoundaryContext> Boundaries { get; set; } = new();



    /// <summary>
    /// Detected dependency relationships between components.
    /// Generated by DependencyDetector.
    /// Evaluators consume this graph instead of discovering dependencies.
    /// </summary>
    public List<ArchitectureDependencyContext> Dependencies { get; set; } = new();

    /// <summary>
    /// Production-to-production relationships used to describe the deployed
    /// architecture. Test-project relationships are intentionally excluded.
    /// </summary>
    public IReadOnlyList<ArchitectureDependencyContext> ProductionDependencies =>
        Dependencies
            .Where(dependency =>
                string.Equals(
                    dependency.Scope,
                    "Production",
                    StringComparison.OrdinalIgnoreCase)
                && !IsTestScopedDependency(dependency))
            .ToArray();

    /// <summary>
    /// Relationships involving at least one test project or test-support module.
    /// These remain available for findings and the relationship ledger, but are
    /// not production architecture edges.
    /// </summary>
    public IReadOnlyList<ArchitectureDependencyContext> TestDependencies =>
        Dependencies
            .Where(dependency =>
                string.Equals(
                    dependency.Scope,
                    "Test",
                    StringComparison.OrdinalIgnoreCase)
                || IsTestScopedDependency(dependency))
            .ToArray();

    private bool IsTestScopedDependency(ArchitectureDependencyContext dependency) =>
        IsTestOrSupportModule(dependency.SourceProjectPath, dependency.Source)
        || IsTestOrSupportModule(dependency.TargetProjectPath, dependency.Target);

    private bool IsTestOrSupportModule(string projectPath, string moduleName)
    {
        ProjectModuleContext? module = null;

        if (!string.IsNullOrWhiteSpace(projectPath))
        {
            var normalizedPath = Path.GetFullPath(projectPath);
            var pathComparison = OperatingSystem.IsWindows()
                ? StringComparison.OrdinalIgnoreCase
                : StringComparison.Ordinal;

            module = Modules.FirstOrDefault(candidate =>
                !string.IsNullOrWhiteSpace(candidate.Path)
                && string.Equals(
                    Path.GetFullPath(candidate.Path),
                    normalizedPath,
                    pathComparison));
        }
        else
        {
            var matchingModules = Modules
                .Where(candidate => string.Equals(
                    candidate.Name,
                    moduleName,
                    StringComparison.OrdinalIgnoreCase))
                .Take(2)
                .ToArray();

            if (matchingModules.Length == 1)
                module = matchingModules[0];
        }

        return module is not null
            && (module.IsTestProject
                || module.IsTestSupport
                || string.Equals(module.Type, "Test", StringComparison.OrdinalIgnoreCase)
                || string.Equals(module.Type, "TestSupport", StringComparison.OrdinalIgnoreCase)
                || string.Equals(module.ProjectKind, "Test", StringComparison.OrdinalIgnoreCase)
                || string.Equals(module.ProjectKind, "TestSupport", StringComparison.OrdinalIgnoreCase));
    }



    // ===============================================================
    // 🧠 Detection Metadata
    // ===============================================================

    public double Confidence { get; set; }


    public string DetectorVersion { get; set; } = "1.4.0";


    public string DetectionStrategy { get; set; } = "Hybrid";


    public Dictionary<string, double> ConfidenceMap { get; set; }
        = new();


    public List<ArchitectureInferenceTrace> InferenceHistory { get; set; }
        = new();

    /// <summary>
    /// Discovery failures that prevented a subtree or file from being examined.
    /// These diagnostics are coverage-affecting and must not be interpreted as
    /// evidence that the excluded area is compliant.
    /// </summary>
    public List<AnalysisDiagnostic> DiscoveryDiagnostics { get; set; } = [];

    /// <summary>
    /// Counts excluded path entries by reason. An excluded directory is counted
    /// once as a subtree boundary; its descendants are not expanded into file counts.
    /// </summary>
    public Dictionary<string, int> ExcludedEntriesByReason { get; set; }
        = new(StringComparer.OrdinalIgnoreCase);



    // ===============================================================
    // 📊 Project Statistics
    // ===============================================================

    public int FileCount { get; set; }

    public int LinesOfCode { get; set; }

    public double AverageComplexity { get; set; }



    // ===============================================================
    // 🌍 Environment
    // ===============================================================

    public Dictionary<string, string> MetadataMap { get; set; }
        = new();


    public bool IsDockerized =>
        MetadataMap.TryGetValue("Dockerized", out var value)
        && value == "true";


    public bool UsesKubernetes =>
        MetadataMap.TryGetValue("Kubernetes", out var value)
        && value == "true";


    public bool IsDeployable =>
        IsDockerized || UsesKubernetes;



    // ===============================================================
    // Compatibility Helpers
    // ===============================================================

    public string? Layer =>
        Layers.Count == 1
            ? Layers[0].Name
            : null;



    public ProjectArchitectureContext()
    {
    }


    public ProjectArchitectureContext(
        string language,
        string? framework,
        double confidence)
    {
        Language = language;
        Framework = framework;
        Confidence = confidence;
    }



    public override string ToString()
    {
        return
            $"{Language}/{Framework ?? "Unknown"} " +
            $"({Confidence:P0}) " +
            $"[{ArchitectureStyle ?? "Unknown"}]";
    }



    public object ToSummaryDto() =>
        new
        {
            ProjectName,
            RootPath,
            Language,
            Framework,
            TargetRuntime,
            BuildSystem = BuildSystem.ToString(),

            Modules = ProductionModules.Count,
            TestProjects = TestModules.Count,
            TestSupportModules = TestSupportModules.Count,
            Layers = Layers.Select(x => x.Name),

            ArchitectureStyle,
            PatternsDetected,

            BoundaryCount = Boundaries.Count,
            DependencyCount = Dependencies.Count,
            ProductionDependencyCount = ProductionDependencies.Count,
            TestDependencyCount = TestDependencies.Count,

            Confidence,
            DetectionStrategy,
            DetectorVersion
        };
}